CREATE TABLE sources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    public_id UUID NOT NULL,
    collection_id BIGINT NOT NULL,
    original_filename VARCHAR(255) NOT NULL,
    object_key VARCHAR(1024) NOT NULL,
    content_type VARCHAR(50) NOT NULL,
    size_bytes BIGINT NOT NULL,
    sha256 VARCHAR(64) NOT NULL,
    status VARCHAR(50) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT pk_sources PRIMARY KEY (id),
    CONSTRAINT uk_sources_public_id UNIQUE (public_id),
    CONSTRAINT uk_sources_object_key UNIQUE (object_key),
    CONSTRAINT fk_sources_collection
        FOREIGN KEY (collection_id)
        REFERENCES knowledge_collections (id)
        ON DELETE RESTRICT,
    CONSTRAINT ck_sources_content_type
        CHECK (content_type IN ('MARKDOWN')),
    CONSTRAINT ck_sources_size_bytes
        CHECK (size_bytes > 0),
    CONSTRAINT ck_sources_sha256
        CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_sources_status
        CHECK (status IN ('PENDING_UPLOAD', 'STORED', 'READY', 'FAILED', 'PROCESSING'))
);

CREATE INDEX idx_sources_collection_id
    ON sources (collection_id);
