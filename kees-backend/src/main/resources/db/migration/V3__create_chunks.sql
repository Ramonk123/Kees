CREATE TABLE chunks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    public_id UUID NOT NULL,
    source_id BIGINT NOT NULL,
    sequence_number INTEGER NOT NULL,
    content TEXT NOT NULL,
    heading_path VARCHAR(1000),
    content_hash VARCHAR(64) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT pk_chunks PRIMARY KEY (id),
    CONSTRAINT uk_chunks_public_id UNIQUE (public_id),
    CONSTRAINT uk_chunks_source_sequence_number
        UNIQUE (source_id, sequence_number),
    CONSTRAINT fk_chunks_source
        FOREIGN KEY (source_id)
        REFERENCES sources (id)
        ON DELETE CASCADE,
    CONSTRAINT ck_chunks_sequence_number
        CHECK (sequence_number >= 0),
    CONSTRAINT ck_chunks_content_not_blank
        CHECK (btrim(content) <> ''),
    CONSTRAINT ck_chunks_content_hash
        CHECK (content_hash ~ '^[0-9a-f]{64}$')
);
